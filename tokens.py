# -*- coding: utf-8 -*-
"""Inkstone 设计 token —— 印刷优先、中文优先的唯一取值来源。

和屏幕图表 token 的三处根本差异：
  1. 单位是 pt 不是 px。1pt = 1/72 in，SVG 用户单位直接当 pt 用，
     导出 PDF 时 1:1 落到纸上；不存在 devicePixelRatio 这回事。
  2. 字号走中文号数体系（五号 10.5pt、小五 9pt、六号 7.5pt），
     不是任意 px 值。排版工种看得懂号数，看不懂 13px。
  3. 没有动画。整个概念在印刷里不存在，规则表因此少一大块。
"""

MM = 2.834645669  # 1mm 的 pt 数


# ─────────────────────────────────────────────────────────────
# 版心：图的宽度不是想多宽多宽，是由载体的栏宽决定的
# ─────────────────────────────────────────────────────────────
COLUMN = {
    "single":  85 * MM,    # 期刊单栏，最常见的配图宽度
    "onehalf": 114 * MM,   # 期刊 1.5 栏
    "double":  170 * MM,   # 期刊双栏 / 跨栏大图
    "a4body":  156 * MM,   # A4 正文宽（210 - 2×27），研报 / 汇报文档
    "slide":   254 * MM,   # 16:9 幻灯片正文宽（内缩后）
}

# 常用高宽比。印刷图不该比正文栏高太多，否则跨页。
RATIO = {"flat": 0.42, "normal": 0.62, "tall": 0.80, "square": 1.0}


# ─────────────────────────────────────────────────────────────
# 字号：中文号数制。CJK 的下限比拉丁高——同样 6.5pt，
# 拉丁字母还能认，"矚" 是一团墨。这是本项目和屏幕图表库最硬的分野。
# ─────────────────────────────────────────────────────────────
SIZE = {
    "title":    10.5,  # 五号 —— 图题
    "subtitle":  9.0,  # 小五 —— 副题，图例和口径写这里
    "label":     7.5,  # 六号 —— 轴标签、类目名（CJK 下限）
    "value":     8.0,  # 图内数值
    "source":    7.5,  # 来源行。见下方注释：6.5 这一档对中文不存在
}
# 中文优先意味着 MIN_CJK_PT 以下的字号档对正文型文本是不存在的：
# text() 会把它们静默抬到 7.5pt。与其留一个永远用不上的 6.5，
# 不如让 token 说实话，来源行的层级差别改由字色和字重承担。
MIN_CJK_PT = 7.5    # 含中日韩字符的文本不得低于此值
MIN_LATIN_PT = 6.0  # 纯拉丁/数字文本的下限

WEIGHT = {"title": 600, "value": 600, "label": 400, "source": 500}


# ─────────────────────────────────────────────────────────────
# 字体栈：中西文必须分开指定。
# PingFang 自带的拉丁字形又窄又飘，数字尤其难看；反过来 Inter
# 没有汉字。SVG 的 font-family 是逐字符 fallback 的，所以
# 把拉丁字体放前面、中文字体放后面，就能自动中西分家。
# ─────────────────────────────────────────────────────────────
FONT_SANS = "'Inter','Helvetica Neue','PingFang SC','Source Han Sans SC','Noto Sans SC','Hiragino Sans GB',sans-serif"
FONT_SERIF = "'Songti SC','Source Han Serif SC','Noto Serif SC',serif"
FONT_NUM = FONT_SANS  # 数字跟随无衬线栈，靠 tabular-nums 对齐


# ─────────────────────────────────────────────────────────────
# 灰阶：默认全灰。印刷单色成本最低、传真影印不失真、必然色盲安全。
# 相邻两级亮度差 ≥ 12%，最浅一级不浅于 15% K —— 再浅胶印会丢网点。
# ─────────────────────────────────────────────────────────────
PAPER = "#FFFFFF"   # 纸就是白的。屏幕图表爱用的暖灰底在印刷上是多余的一层墨。

# 灰阶按 CIE L* 等距反解，不是拍脑袋写 hex——L* 感知均匀，
# 相邻两级差 13 L*，远高于 10 L* 的可分辨门槛，缩印和影印后仍分得开。
# 0–3 是文字安全档（对白 ≥4.5:1），4–6 只许作填充。用错档校验器会拦。
GRAY = [
    "#1F1F1F",  # 0  L*12  16.4:1  主数据 / 最重要
    "#3B3B3B",  # 1  L*25  11.2:1  次要数据 / 类目名
    "#575757",  # 2  L*37   7.2:1  副题
    "#747474",  # 3  L*49   4.6:1  文字安全线，来源行到此为止
    "#969696",  # 4  L*62   3.0:1  ── 以下仅填充 ──
    "#BBBBBB",  # 5  L*76   1.9:1  次要填充
    "#DDDDDD",  # 6  L*88   1.4:1  底槽 / 网格
]
TEXT_SAFE_MAX = 3   # GRAY 下标 >3 不得用于 <text>

INK = GRAY[0]
MUTED = GRAY[2]     # 副题
SRC = GRAY[3]       # 来源行
RULE = GRAY[6]
TRACK = GRAY[6]
FAINT = GRAY[4]


# ─────────────────────────────────────────────────────────────
# 线宽（pt）：0.25pt 以下激光打印和胶印都会断，定 0.35 为地板。
# ─────────────────────────────────────────────────────────────
STROKE = {
    "hairline": 0.35,  # 发丝线（逐记录图的基本笔画）
    "rule":     0.5,   # 分隔线 / 轴线
    "data":     1.0,   # 一般数据线
    "bold":     2.0,   # 强调线
}

# ─────────────────────────────────────────────────────────────
# 点（pt）：实心点直径小于 0.7pt（≈0.25mm）时激光打印会丢、胶印会虚。
# 半径地板取 0.35pt，和线宽地板同源。
# ─────────────────────────────────────────────────────────────
DOT = {"min_r": 0.35, "r": 1.6, "gap": 0.4}

# ─────────────────────────────────────────────────────────────
# 热力档位：灰阶做连续标度不可靠——人眼在无参照时分不出 60% 灰和
# 68% 灰。所以量化成 5 档，并在格内直接标数值。
#
# 档位要跳过 L*50–56 这条死区：在这一带，深字对底不到 4.5:1，白字
# 也不到 4.5:1，两种文字色都不合格。一条要在格内承载数字的标度，
# 宁可牺牲档间的感知等距，也不能落进死区。
# ─────────────────────────────────────────────────────────────
HEAT = [GRAY[6], GRAY[5], GRAY[4], GRAY[1], GRAY[0]]   # 由浅到深 5 档
HEAT_FLIP = 3   # 下标 ≥3 的档位是深底，格内文字要翻成纸白

# ─────────────────────────────────────────────────────────────
# 间距（pt）
# ─────────────────────────────────────────────────────────────
PAD = {"top": 4, "right": 6, "bottom": 14, "left": 6}
GAP = {"title_sub": 4, "sub_plot": 12, "plot_source": 10}


def px(pt: float) -> float:
    """SVG 用户单位就是 pt，留这个函数是为了让调用处读得出意图。"""
    return round(pt, 3)
