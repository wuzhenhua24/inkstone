"""Inkstone 设计 token —— 印刷优先、中文优先的唯一取值来源。

和屏幕图表 token 的三处根本差异：
  1. 单位是 pt 不是 px。1pt = 1/72 in，SVG 用户单位直接当 pt 用，
     导出 PDF 时 1:1 落到纸上；不存在 devicePixelRatio 这回事。
  2. 字号走中文号数体系（五号 10.5pt、小五 9pt、六号 7.5pt），
     不是任意 px 值。排版工种看得懂号数，看不懂 13px。
  3. 没有动画。整个概念在印刷里不存在，规则表因此少一大块。
"""

MM = 2.834645669  # 1mm 的 pt 数


