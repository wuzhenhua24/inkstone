# ─────────────────────────────────────────────────────────────
# 灰阶：默认全灰。印刷单色成本最低、传真影印不失真、必然色盲安全。
# 相邻两级亮度差 ≥ 12%，最浅一级不浅于 15% K —— 再浅胶印会丢网点。
# ─────────────────────────────────────────────────────────────
PAPER = "#FFFFFF"   # 纸就是白的。屏幕图表爱用的暖灰底在印刷上是多余的一层墨。

# 灰阶按 CIE L* 等距反解，不是拍脑袋写 hex——L* 感知均匀，
# 相邻两级差 13 L*，远高于 10 L* 的可分辨门槛，缩印和影印后仍分得开。
# 0–3 是文字安全档（对白 ≥4.5:1），4–6 只许作填充。用错档校验器会拦。
GRAY = [
    "#1F1F1F",  # 0  L*12  16.4:1  主数据 / 最重要
    "#3B3B3B",  # 1  L*25  11.2:1  次要数据 / 类目名
    "#575757",  # 2  L*37   7.2:1  副题
    "#747474",  # 3  L*49   4.6:1  文字安全线，来源行到此为止
    "#969696",  # 4  L*62   3.0:1  ── 以下仅填充 ──
    "#BBBBBB",  # 5  L*76   1.9:1  次要填充
    "#DDDDDD",  # 6  L*88   1.4:1  底槽 / 网格
]
TEXT_SAFE_MAX = 3   # GRAY 下标 >3 不得用于 <text>

MONO = list(GRAY)   # 留一份原始灰阶，切色板后还能切回来
ACTIVE = "mono"     # 当前色板名，会写进 SVG 供校验器取尺


def _derive():
    """从当前 GRAY 重算所有派生色。切换色板后必须调用。

    派生色一律在这里集中算，不许各图型自己在模块顶层缓存一份——
    那样的副本不会跟着色板走，切色后就成了灰色的孤儿。
    """
    g = globals()
    g["INK"] = GRAY[0]
    g["MUTED"] = GRAY[2]     # 副题
    g["SRC"] = GRAY[3]       # 来源行
    g["RULE"] = GRAY[6]
    g["TRACK"] = GRAY[6]
    g["FAINT"] = GRAY[4]
    # 热力 5 档：跳过 L*50–56 死区（见下方注释）
    g["HEAT"] = [GRAY[6], GRAY[5], GRAY[4], GRAY[1], GRAY[0]]
    g["HEAT_FLIP"] = 3       # 下标 ≥3 是深底，格内文字翻成纸白
    # 堆叠带 5 档：相邻 ≥12 L*，每档都存在对比度 ≥4.5:1 的文字色
    g["BAND"] = [GRAY[0], GRAY[2], GRAY[4], GRAY[5], GRAY[6]]
    g["BAND_FLIP"] = 2


_derive()


class use:
    """切换彩色档。色相变，L* 不变——影印成灰度后和 mono 版是同一张。

        with T.use("indigo"):
            svg = rank_bars(...)

    没有 with 的话切换是全局的，记得切回 "mono"。
    """

    def __init__(self, name):
        import palettes
        self.ramp = palettes.build(name)
        self.name = name
        self.prev = None

    def __enter__(self):
        self.prev, self.prev_name = list(GRAY), ACTIVE
        GRAY[:] = self.ramp if self.ramp else MONO
        globals()["ACTIVE"] = self.name
        _derive()
        return self

    def __exit__(self, *exc):
        GRAY[:] = self.prev
        globals()["ACTIVE"] = self.prev_name
        _derive()
        return False


